/**
 * Design units: every W Design canvas is laid out on a 360-unit-wide reference, so 1 unit = 3 px
 * in MAML's 1080-wide coordinate space (screenWidth="1080"; MAML rescales to the real screen).
 */
const val MAML_WIDTH = 1080
const val UNIT_TO_MAML = MAML_WIDTH / 360f

/** An image the Android render layer must produce so the MAML manifest can reference it. */
sealed class MamlAssetRequest {
    abstract val files: List<String>

    /** The lock wallpaper without clock/decorations, at device resolution. */
    data class Background(val file: String, val widthPx: Int, val heightPx: Int) : MamlAssetRequest() {
        override val files get() = listOf(file)
    }

    /** A glass panel: the blurred wallpaper region under [element], tinted, rounded, with hairline. */
    data class GlassPanel(val file: String, val element: CanvasElement, val widthPx: Int, val heightPx: Int) : MamlAssetRequest() {
        override val files get() = listOf(file)
    }

    /** Any element drawn exactly as in the preview (images, rotated shapes, text in non-system fonts). */
    data class RasterElement(val file: String, val element: CanvasElement, val widthPx: Int, val heightPx: Int) : MamlAssetRequest() {
        override val files get() = listOf(file)
    }

    /** Clock digits time_0..9 + time_dot rasterized in the design's font/render style. */
    data class DigitSet(val prefix: String, val clock: ClockSpec, val sizePx: Int) : MamlAssetRequest() {
        override val files get() = (0..9).map { "${prefix}_$it.png" } + "${prefix}_dot.png"
    }
}

enum class MamlNote { FOD_OVERLAP_HIDDEN, WIDGET_PREVIEW_ONLY, CLOCK_AS_IMAGES, ROTATION_RASTERIZED, TEXT_RASTERIZED, GRADIENT_AS_IMAGES, DATE_PATTERN_SIMPLIFIED }

data class MamlPlan(
    val manifestXml: String,
    val requests: List<MamlAssetRequest>,
    val notes: List<Pair<MamlNote, String>>,
)

/** Generates a MAML lock screen (lockscreen/advance/manifest.xml) from a Lock Screen Studio design. */
object MamlLockscreenGenerator {

    private fun f(v: Float) = String.format(Locale.ROOT, "%.1f", v)
    private fun fy(frac: Float) = "#screen_height*" + String.format(Locale.ROOT, "%.4f", frac)

    /** HyperOS/MIUI system font family names used by community MAML themes (see docs/MTZ.md). */
    fun miFontFamily(weight: Int): String = when {
        weight <= 200 -> "mipro-extralight"
        weight <= 300 -> "mipro-light"
        weight <= 400 -> "mipro-normal"
        weight <= 500 -> "mipro-medium"
        weight <= 600 -> "mipro-demibold"
        else -> "mipro-bold"
    }

    private val sansFonts = setOf(SystemFont.SANS, SystemFont.SANS_LIGHT, SystemFont.SANS_THIN, SystemFont.SANS_MEDIUM, SystemFont.SANS_BLACK)

    /** True when the clock can be a live system-font <DateTime>; otherwise it becomes image digits. */
    fun clockIsText(c: ClockSpec): Boolean =
        (c.render == ClockRender.TEXT || c.render == ClockRender.STACKED) && c.font in sansFonts && c.gradient.isNullOrEmpty()

    private fun alignAttr(a: TextAlign) = when (a) { TextAlign.START -> "left"; TextAlign.CENTER -> "center"; TextAlign.END -> "right" }

    fun plan(spec: LockScreenSpec, screenW: Int, screenH: Int, unlockHint: String = "Swipe up to unlock"): MamlPlan {
        val mamlH = (screenH * MAML_WIDTH.toFloat() / screenW).roundToInt()
        val aspect = screenH.toFloat() / screenW
        val requests = mutableListOf<MamlAssetRequest>()
        val notes = mutableListOf<Pair<MamlNote, String>>()
        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        sb.append("<!-- Generated by W Design. Unofficial theme, not verified or signed by Xiaomi. -->\n")
        sb.append("<Lockscreen version=\"2\" frameRate=\"30\" screenWidth=\"$MAML_WIDTH\" useVariableUpdater=\"DateTime.Minute\" useHardwareCanvas=\"true\">\n")

        // Background: the design's lock wallpaper, rendered without clock and decorations.
        requests += MamlAssetRequest.Background("bg.jpg", screenW, screenH)
        sb.append("  <Image name=\"wd_bg\" x=\"0\" y=\"0\" w=\"#screen_width\" h=\"#screen_height\" src=\"bg.jpg\"/>\n")

        val fod = spec.fodArea
        fun fodVisibility(e: CanvasElement): String {
            if (!e.overlapsCircle(fod.x, fod.y, fod.r, aspect)) return ""
            notes += MamlNote.FOD_OVERLAP_HIDDEN to e.id
            return " visibility=\"#fod_enable==0\""
        }

        for (e in spec.elements.filter { !it.hidden }.sortedBy { it.z }) {
            val x = e.x * MAML_WIDTH; val w = e.w * MAML_WIDTH
            val h = e.h * mamlH
            val alpha = (e.opacity.coerceIn(0f, 1f) * 255).roundToInt()
            val vis = fodVisibility(e)
            val pxW = (e.w * screenW).roundToInt().coerceAtLeast(1)
            val pxH = (e.h * screenH).roundToInt().coerceAtLeast(1)
            val alphaAttr = if (alpha < 255) " alpha=\"$alpha\"" else ""
            val name = "wd_" + e.id.filter { it.isLetterOrDigit() || it == '_' }
            fun imageTag(file: String) =
                "  <Image name=\"$name\" x=\"${f(x)}\" y=\"${fy(e.y)}\" w=\"${f(w)}\" h=\"${f(h)}\" src=\"$file\"$alphaAttr$vis/>\n"
            when (e.type) {
                ElementType.WIDGET_REF, ElementType.ICON_GRID -> notes += MamlNote.WIDGET_PREVIEW_ONLY to e.id
                ElementType.CLOCK, ElementType.DATE -> Unit // the dedicated clock/date specs are used instead
                ElementType.GLASS_PANEL -> {
                    val file = "deco/glass_${e.id}.png"
                    requests += MamlAssetRequest.GlassPanel(file, e, pxW, pxH)
                    sb.append(imageTag(file))
                }
                ElementType.IMAGE -> {
                    val file = "deco/img_${e.id}.png"
                    requests += MamlAssetRequest.RasterElement(file, e, pxW, pxH)
                    sb.append(imageTag(file))
                }
                ElementType.SHAPE -> {
                    if (e.rotation != 0f) {
                        notes += MamlNote.ROTATION_RASTERIZED to e.id
                        val file = "deco/shape_${e.id}.png"
                        requests += MamlAssetRequest.RasterElement(file, e, pxW, pxH)
                        sb.append(imageTag(file))
                    } else {
                        val fill = e.color(Props.FILL, ArgbColor.White.withAlpha(0.3f)).toHex()
                        val stroke = e.prop(Props.STROKE)?.let(ArgbColor::parse)
                        val strokeAttr = if (stroke != null) " strokeColor=\"${stroke.toHex()}\" weight=\"3\" strokeAlign=\"inner\"" else ""
                        when (e.prop(Props.SHAPE) ?: "rect") {
                            "circle" -> {
                                val r = minOf(w, h) / 2f
                                sb.append("  <Circle name=\"$name\" x=\"${f(x + w / 2)}\" y=\"${fy(e.centerY)}\" r=\"${f(r)}\" fillColor=\"$fill\"$strokeAttr$alphaAttr$vis/>\n")
                            }
                            else -> {
                                val corner = if (e.prop(Props.SHAPE) == "pill") minOf(w, h) / 2f else e.float(Props.CORNER, 0f) * UNIT_TO_MAML
                                sb.append("  <Rectangle name=\"$name\" x=\"${f(x)}\" y=\"${fy(e.y)}\" w=\"${f(w)}\" h=\"${f(h)}\" cornerRadius=\"${f(corner)},${f(corner)}\" fillColor=\"$fill\"$strokeAttr$alphaAttr$vis/>\n")
                            }
                        }
                    }
                }
                ElementType.TEXT -> {
                    val font = e.prop(Props.FONT)?.let { runCatching { SystemFont.valueOf(it) }.getOrNull() } ?: SystemFont.SANS
                    if (e.rotation != 0f || font !in sansFonts) {
                        notes += MamlNote.TEXT_RASTERIZED to e.id
                        val file = "deco/text_${e.id}.png"
                        requests += MamlAssetRequest.RasterElement(file, e, pxW, pxH)
                        sb.append(imageTag(file))
                    } else {
                        val size = e.float(Props.FONT_SIZE, 16f) * UNIT_TO_MAML
                        val color = e.color(Props.COLOR, ArgbColor.White).toHex()
                        val align = e.prop(Props.ALIGN)?.let { runCatching { TextAlign.valueOf(it) }.getOrNull() } ?: TextAlign.START
                        val ax = when (align) { TextAlign.START -> x; TextAlign.CENTER -> x + w / 2; TextAlign.END -> x + w }
                        val weight = e.prop(Props.WEIGHT)?.toIntOrNull() ?: font.weight
                        sb.append("  <Text name=\"$name\" x=\"${f(ax)}\" y=\"${fy(e.y)}\" align=\"${alignAttr(align)}\" alignV=\"top\" color=\"$color\" size=\"${f(size)}\" fontFamily=\"${miFontFamily(weight)}\" text=\"${esc(e.prop(Props.TEXT).orEmpty())}\"$alphaAttr$vis/>\n")
                    }
                }
            }
        }

        // Date
        val d = spec.date
        if (d.visible) {
            val dx = d.x * MAML_WIDTH
            val tr = MamlDatePattern.translate(d.pattern)
            if (tr.simplified) notes += MamlNote.DATE_PATTERN_SIMPLIFIED to tr.dropped.joinToString("")
            sb.append("  <DateTime name=\"wd_date\" x=\"${f(dx)}\" y=\"${fy(d.y)}\" align=\"${alignAttr(d.align)}\" alignV=\"top\" color=\"${d.color.toHex()}\" size=\"${f(d.sizeSp * UNIT_TO_MAML)}\" fontFamily=\"mipro-normal\" format=\"${esc(tr.pattern)}\"/>\n")
        }

        // Clock
        val c = spec.clock
        if (c.visible) {
            val cx = c.x * MAML_WIDTH
            val sizePx = c.sizeSp * UNIT_TO_MAML
            val stacked = c.render == ClockRender.STACKED
            val lines: List<Pair<String, String>> = if (stacked) listOf("HH" to "hh", "mm" to "mm") else listOf("HH:mm" to "hh:mm")
            val lineStep = sizePx * 0.95f / mamlH
            if (clockIsText(c)) {
                val family = miFontFamily(c.weight)
                lines.forEachIndexed { i, (f24, f12) ->
                    val fmt = when (c.format) {
                        ClockFormat.FOLLOW_SYSTEM -> "formatExp=\"ifelse(#time_format,'$f24','$f12')\""
                        ClockFormat.H24 -> "format=\"$f24\""
                        ClockFormat.H12 -> "format=\"$f12\""
                    }
                    sb.append("  <DateTime name=\"wd_clock$i\" x=\"${f(cx)}\" y=\"${fy(c.y + i * lineStep)}\" align=\"${alignAttr(c.align)}\" alignV=\"top\" color=\"${c.color.toHex()}\" size=\"${f(sizePx)}\" fontFamily=\"$family\" $fmt/>\n")
                }
            } else {
                notes += (if (!c.gradient.isNullOrEmpty()) MamlNote.GRADIENT_AS_IMAGES else MamlNote.CLOCK_AS_IMAGES) to "clock"
                val prefix = "clock/time"
                requests += MamlAssetRequest.DigitSet(prefix, c, (c.sizeSp * screenW / 360f).roundToInt())
                lines.forEachIndexed { i, (f24, f12) ->
                    val y = fy(c.y + i * lineStep)
                    val common = "x=\"${f(cx)}\" y=\"$y\" align=\"${alignAttr(c.align)}\" src=\"$prefix.png\""
                    when (c.format) {
                        ClockFormat.FOLLOW_SYSTEM -> {
                            sb.append("  <Time name=\"wd_time24_$i\" $common format=\"$f24\" visibility=\"#time_format\"/>\n")
                            sb.append("  <Time name=\"wd_time12_$i\" $common format=\"$f12\" visibility=\"!#time_format\"/>\n")
                        }
                        ClockFormat.H24 -> sb.append("  <Time name=\"wd_time_$i\" $common format=\"$f24\"/>\n")
                        ClockFormat.H12 -> sb.append("  <Time name=\"wd_time_$i\" $common format=\"$f12\"/>\n")
                    }
                }
            }
        }

        // Unlock: the documented swipe-up pattern. The system bouncer (PIN, pattern, biometrics)
        // still runs after ExternCommand unlock; W Design never provides its own password UI.
        val hint = unlockHint.ifBlank { "Swipe up to unlock" }
        sb.append("  <Text name=\"wd_hint\" x=\"540\" y=\"#screen_height-150\" align=\"center\" alignV=\"center\" color=\"#B3FFFFFF\" size=\"36\" fontFamily=\"mipro-normal\" text=\"${esc(hint)}\"/>\n")
        sb.append("  <Button name=\"wd_unlock\" x=\"0\" y=\"0\" w=\"#screen_width\" h=\"#screen_height\">\n")
        sb.append("    <Triggers>\n")
        sb.append("      <Trigger action=\"up\">\n")
        sb.append("        <ExternCommand command=\"unlock\" condition=\"max(#touch_begin_y-#touch_y,0)}=300\"/>\n")
        sb.append("      </Trigger>\n")
        sb.append("    </Triggers>\n")
        sb.append("  </Button>\n")
        sb.append("</Lockscreen>\n")
        return MamlPlan(sb.toString(), requests, notes)
    }
}

/** Optional (experimental) MAML wallpaper for the "miwallpaper" module, from a live wallpaper design. */
object MiWallpaperGenerator {
    private fun f(v: Float) = String.format(Locale.ROOT, "%.1f", v)

    fun generate(live: LiveWallpaperSpec): String {
        val colors = live.colors.ifEmpty { listOf(ArgbColor.Black, ArgbColor.White) }
        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        sb.append("<!-- Generated by W Design (experimental). Unofficial, not verified by Xiaomi. -->\n")
        sb.append("<MiWallpaper version=\"1\" frameRate=\"30\" screenWidth=\"$MAML_WIDTH\" useVariableUpdater=\"DateTime.Minute\">\n")
        sb.append("  <Rectangle x=\"0\" y=\"0\" w=\"#screen_width\" h=\"#screen_height\">\n")
        sb.append("    <FillShaders>\n")
        sb.append("      <LinearGradient x=\"0\" y=\"0\" x1=\"#screen_width\" y1=\"#screen_height\" tile=\"clamp\">\n")
        colors.forEachIndexed { i, c ->
            val pos = if (colors.size == 1) 0f else i.toFloat() / (colors.size - 1)
            sb.append("        <GradientStop color=\"${c.toHex()}\" position=\"${String.format(Locale.ROOT, "%.2f", pos)}\"/>\n")
        }
        sb.append("      </LinearGradient>\n")
        sb.append("    </FillShaders>\n")
        sb.append("  </Rectangle>\n")
        val rnd = java.util.Random(live.count.toLong() * 31 + live.type.ordinal)
        val n = when (live.type) { LiveType.PARTICLES -> live.count.coerceIn(4, 24); LiveType.GRADIENT_FLOW -> 4; LiveType.DEPTH_LAYERS -> 6 }
        val baseDuration = (12000 / (0.2f + live.speed)).roundToInt()
        repeat(n) { i ->
            val c = colors[(i + 1) % colors.size]
            val x = rnd.nextFloat() * MAML_WIDTH
            val y = rnd.nextFloat() * 2200f
            val r = when (live.type) { LiveType.PARTICLES -> 6f + rnd.nextFloat() * 18f; LiveType.GRADIENT_FLOW -> 260f + rnd.nextFloat() * 220f; LiveType.DEPTH_LAYERS -> 120f + i * 40f }
            val a = (40 + live.intensity * 120).roundToInt().coerceIn(20, 200)
            val dur = baseDuration + rnd.nextInt(4000)
            val dx = (rnd.nextFloat() - 0.5f) * 240f
            val dy = -(80f + rnd.nextFloat() * 320f)
            sb.append("  <Circle x=\"${f(x)}\" y=\"${f(y)}\" r=\"${f(r)}\" fillColor=\"${c.withAlpha(a).toHex()}\">\n")
            sb.append("    <PositionAnimation>\n")
            sb.append("      <Item x=\"0\" y=\"0\" time=\"0\"/>\n")
            sb.append("      <Item x=\"${f(dx)}\" y=\"${f(dy)}\" time=\"${dur / 2}\"/>\n")
            sb.append("      <Item x=\"0\" y=\"0\" time=\"$dur\"/>\n")
            sb.append("    </PositionAnimation>\n")
            sb.append("    <AlphaAnimation>\n")
            sb.append("      <Item value=\"255\" time=\"0\"/>\n")
            sb.append("      <Item value=\"120\" time=\"${dur / 2}\"/>\n")
            sb.append("      <Item value=\"255\" time=\"$dur\"/>\n")
            sb.append("    </AlphaAnimation>\n")
            sb.append("  </Circle>\n")
        }
        sb.append("</MiWallpaper>\n")
        return sb.toString()
    }
}
